/**
 * Curates the Iconify icon sets used by the client into a tiny module.
 *
 * The full `@iconify-json/<set>` JSON files would inflate the client bundle
 * enormously if imported directly (Vite cannot tree-shake nested object keys in
 * JSON). Instead, this script reads the installed sets at authoring time and
 * writes `client/src/lib/components/ui/curated-icons.ts` containing ONLY the
 * icons the app references (a few KB).
 *
 * When you use a new Iconify icon, add it to `CURATED` below and re-run
 * `npm run icons:curate` (root).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

/** Iconify name (without the `prefix:`) to keep, grouped by set prefix. */
const CURATED = {
  mdi: ["home", "menu", "settings", "close", "search", "check"],
};

function loadSet(prefix) {
  const pkg = `@iconify-json/${prefix}`;
  const file = join(ROOT, "node_modules", pkg, "icons.json");
  return JSON.parse(readFileSync(file, "utf8"));
}

const collections = [];
for (const [prefix, names] of Object.entries(CURATED)) {
  const set = loadSet(prefix);
  const icons = {};
  for (const name of names) {
    if (set.icons?.[name] !== undefined) {
      icons[name] = set.icons[name];
    } else {
      console.warn(`[curate-icons] missing ${prefix}:${name}`);
    }
  }
  // Keep aliases whose parent is curated (so e.g. "settings" variants work).
  const aliases = {};
  for (const [alias, value] of Object.entries(set.aliases ?? {})) {
    if (icons[value.parent] !== undefined) {
      aliases[alias] = value;
    }
  }
  collections.push({
    prefix,
    icons,
    ...(Object.keys(aliases).length > 0 ? { aliases } : {}),
    ...(set.width !== undefined ? { width: set.width } : {}),
    ...(set.height !== undefined ? { height: set.height } : {}),
  });
}

const body = `// AUTO-GENERATED by scripts/curate-icons.mjs — do not edit by hand.
// Regenerate with: npm run icons:curate (root).

/** Curated Iconify collections (only the icons this app uses — small bundle). */
export const CURATED_ICONS: ReadonlyArray<{
  prefix: string;
  icons: Record<string, { body: string }>;
  aliases?: Record<string, { parent: string }>;
  width?: number;
  height?: number;
}> = ${JSON.stringify(collections, null, 2)};
`;

const outDir = join(ROOT, "client", "src", "lib", "components", "ui");
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, "curated-icons.ts");
writeFileSync(outFile, body, "utf8");
console.log(
  `[curate-icons] wrote ${outFile} (${collections.reduce((n, c) => n + Object.keys(c.icons).length, 0)} icons)`,
);
